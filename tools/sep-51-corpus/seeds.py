def _seed(type_name, ios_type, json_value, note, oracle=None, spec_form=None,
          spec_form_paths=None, input_variants=None, non_utf8_paths=None,
          xdr=None):
    seed = {
        "type": type_name,
        "ios_type": ios_type,
        "json": json_value,
        "note": note,
    }
    if oracle is not None:
        seed["oracle"] = oracle
    if spec_form is not None:
        seed["spec_form"] = spec_form
    if spec_form_paths is not None:
        seed["spec_form_paths"] = spec_form_paths
    if input_variants is not None:
        seed["input_variants"] = input_variants
    if non_utf8_paths is not None:
        seed["non_utf8_paths"] = non_utf8_paths
    if xdr is not None:
        seed["xdr"] = xdr
    return seed


