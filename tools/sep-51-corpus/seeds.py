"""Hand-authored seeds for the SEP-0051 (XDR-JSON) conformance corpus.

Each seed is a dict:

  type        Reference CLI type name (ScVal), the spelling `stellar-xdr` uses.
  ios_type    SDK type name (SCValXDR). `../sep-51-oracle/type_map.json` is the
              sole authority on the pairing; the two spellings differ in acronym
              case, in the reserved-name escape and in this SDK's XDR suffix, and
              a missing mapping fails the run rather than falling back to a guess.
  json        The value written in the reference's own XDR-JSON form. The corpus
              generator encodes it with the reference CLI, so a document that is
              not valid XDR-JSON for that type fails the build.
  note        One sentence naming the shape the seed pins.
  oracle      Optional. "incomparable" marks a rendering where the SDK follows
              SEP-0051 and the reference does not; such a seed also carries
              spec_form and spec_form_paths. "spec" marks a value the pinned
              reference cannot resolve at all, which the generator admits only
              for a name the oracle's own unresolvable list carries.
  spec_form   Required with "incomparable". Names the transformation the
              generator applies to the reference's output to derive what the SDK
              must emit: "integer_string" or "opaque_hex".
  spec_form_paths
              Required with "incomparable", with no exemption. The JSON paths the
              transformation is expected to rewrite, dotted for object keys and
              [n] for array indices; the empty string names the whole document,
              which is what integer_string rewrites. A union arm key is an
              ordinary object key, so "ip.i_pv4" addresses an arm payload. A seed
              whose transformation rewrites nothing declares the empty list; an
              omitted field is a generation failure, not a default. The generator
              fails when the declared set and the rewritten set differ in either
              direction, because that is where the byte-array heuristic has caught
              an integer array that is not opaque data.
  input_variants
              Optional. Further JSON documents that must decode to the same XDR.
              The corpus records what the SDK emits and the reference emits one
              spelling per key, so an accepted alternative spelling cannot arrive
              through the normal path; a variant is verified by encoding it with
              the reference and requiring the same base64, which keeps it
              oracle-verified. Incomparable seeds may not carry variants.
  non_utf8_paths
              Optional. The JSON paths, in the syntax spec_form_paths uses, whose
              escape-ladder bytes are deliberately not valid UTF-8. Admissible
              only where the field is opaque and therefore byte-exact; see the
              UTF-8 rule below. The generator fails when the declared set and the
              set it finds differ in either direction.

A seed value that lands in an XDR `string<>` field must be valid UTF-8 once the
escape ladder is resolved. This SDK models every `string<>` as a Swift `String`,
which is guaranteed well-formed Unicode, so a lone continuation or lead byte can
be round-tripped by the reference but cannot be constructed, decoded or held
here. Opaque fields are unaffected: they are backed by `Data` or `WrappedDataN`
and are byte-exact, which is why the asset codes may carry a bare `\xc3` and
declare it through non_utf8_paths.

No seed may carry a `$schema` property anywhere. The corpus is built by encoding
each seed with the reference, which rejects that property, so such a seed fails
with an error that reads like an SDK bug rather than a reference limitation.
`$schema` acceptance is pinned by a hand-written test instead.

Seeds cover the renderings that are not mechanical: every arm of the unions
whose JSON form is a strkey or a bare name, the integer types rendered as
strings, the SEP-0051 escape ladder over bytes-typed and string-typed fields,
empty and populated variable-length data, optionals in both states, and the
name rules that a pin bump could disturb. They also cover the overlay, internal
and exporter definitions, which this SDK generates and which carry the address
family enum, the reserved-name type escape and a union with inline opaque arms.

A SignerKeyEd25519SignedPayload with a zero-length payload is deliberately
absent: the reference decodes it to a strkey it then refuses to encode, so it
cannot round-trip through the generator. That input is pinned by a hand-written
negative test instead.

Where several XDR definitions share one Swift type and render differently, the
Swift type is never seeded: only the union arm that selects a definition can
render it, so the pair is seeded through that union. Both sides of every such
pair are present, because a fixture exercising one side cannot see a helper that
emits the other side's names.
"""

